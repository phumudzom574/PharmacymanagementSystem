    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        String fullName = jTextField1.getText().trim();
String username = jTextField2.getText().trim();
String password = new String(jPasswordField1.getPassword());
String role = jComboBox1.getSelectedItem().toString();

if (fullName.isEmpty() || username.isEmpty() || password.isEmpty()) {
    JOptionPane.showMessageDialog(
            this,
            "Please fill in all user details.",
            "Missing Information",
            JOptionPane.WARNING_MESSAGE
    );
    return;
}

String sql = "INSERT INTO users (username, password, role, full_name) "
        + "VALUES (?, ?, ?, ?)";

try (
        Connection con = DBConnection.getConnection();
        PreparedStatement pst = con.prepareStatement(sql)
) {

    pst.setString(1, username);
    pst.setString(2, password);
    pst.setString(3, role);
    pst.setString(4, fullName);

    pst.executeUpdate();

    JOptionPane.showMessageDialog(
            this,
            "User added successfully!",
            "Success",
            JOptionPane.INFORMATION_MESSAGE
    );

    jTextField1.setText("");
    jTextField2.setText("");
    jPasswordField1.setText("");

} catch (Exception e) {

    JOptionPane.showMessageDialog(
            this,
            "Database error:\n" + e.getMessage(),
            "Error",
            JOptionPane.ERROR_MESSAGE
    );

    e.printStackTrace();
}
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        int selectedRow = jTable1.getSelectedRow();

if (selectedRow == -1) {
    JOptionPane.showMessageDialog(
            this,
            "Please select a user from the table first.",
            "No User Selected",
            JOptionPane.WARNING_MESSAGE
    );
    return;
}

int userId = (int) jTable1.getValueAt(selectedRow, 0);

int confirm = JOptionPane.showConfirmDialog(
        this,
        "Are you sure you want to delete this user?",
        "Confirm Delete",
        JOptionPane.YES_NO_OPTION
);

if (confirm != JOptionPane.YES_OPTION) {
    return;
}

String sql = "DELETE FROM users WHERE user_id = ?";

try (
        Connection con = DBConnection.getConnection();
        PreparedStatement pst = con.prepareStatement(sql)
) {

    pst.setInt(1, userId);
    pst.executeUpdate();

    JOptionPane.showMessageDialog(
            this,
            "User deleted successfully!",
            "Success",
            JOptionPane.INFORMATION_MESSAGE
    );

    loadUsers();

} catch (Exception e) {

    JOptionPane.showMessageDialog(
            this,
            "Database error:\n" + e.getMessage(),
            "Error",
            JOptionPane.ERROR_MESSAGE
    );

    e.printStackTrace();
}
    }//GEN-LAST:event_jButton2ActionPerformed

