    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
        // TODO add your handling code here:
   DefaultTableModel model = (DefaultTableModel) jTable1.getModel();

if (model.getRowCount() == 0) {
    JOptionPane.showMessageDialog(this,
            "Cart is empty. Please add items first.");
    return;
}

double total = 0;

for (int i = 0; i < model.getRowCount(); i++) {

    Object subtotalValue = model.getValueAt(i, 4);

    if (subtotalValue != null &&
        !subtotalValue.toString().trim().isEmpty()) {

        total += Double.parseDouble(subtotalValue.toString());
    }
}

StringBuilder bill = new StringBuilder();

bill.append("PHARMACY BILL\n\n");

for (int i = 0; i < model.getRowCount(); i++) {

    bill.append("Medicine: ")
        .append(model.getValueAt(i, 1))
        .append("\n");

    bill.append("Price: R")
        .append(model.getValueAt(i, 2))
        .append("\n");

    bill.append("Quantity: ")
        .append(model.getValueAt(i, 3))
        .append("\n");

    bill.append("Subtotal: R")
        .append(model.getValueAt(i, 4))
        .append("\n\n");
}

bill.append("\n");
bill.append(String.format("TOTAL: R%.2f%n", total));
bill.append("\nThank you for your purchase!");

JOptionPane.showMessageDialog(
        this,
        bill.toString(),
        "Generated Bill",
        JOptionPane.INFORMATION_MESSAGE);
    


    }//GEN-LAST:event_jButton4ActionPerformed

