    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
    if (jComboBox1.getSelectedItem() == null) {
        JOptionPane.showMessageDialog(
                this,
                "Please select a medicine.",
                "Missing Medicine",
                JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    String selectedMedicine = jComboBox1.getSelectedItem().toString();

    int medicineId;
    try {
        medicineId = Integer.parseInt(
                selectedMedicine.substring(0, selectedMedicine.indexOf(" -"))
        );
    } catch (Exception e) {
        JOptionPane.showMessageDialog(
                this,
                "Invalid medicine selection.",
                "Error",
                JOptionPane.ERROR_MESSAGE
        );
        return;
    }

    int quantity;

    try {
        quantity = Integer.parseInt(jTextField1.getText().trim());

        if (quantity <= 0) {
            JOptionPane.showMessageDialog(
                    this,
                    "Quantity must be greater than zero.",
                    "Invalid Quantity",
                    JOptionPane.WARNING_MESSAGE
            );
            return;
        }

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(
                this,
                "Please enter a valid quantity.",
                "Invalid Quantity",
                JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    String sql = "SELECT name, price, quantity_in_stock "
            + "FROM medicines WHERE medicine_id = ?";

    try (
        Connection con = DBConnection.getConnection();
        PreparedStatement pst = con.prepareStatement(sql)
    ) {

        pst.setInt(1, medicineId);

        ResultSet rs = pst.executeQuery();

        if (rs.next()) {

            String medicineName = rs.getString("name");
            double price = rs.getDouble("price");
            int stock = rs.getInt("quantity_in_stock");

            if (quantity > stock) {
                JOptionPane.showMessageDialog(
                        this,
                        "Not enough stock available.\n"
                        + "Available stock: " + stock,
                        "Insufficient Stock",
                        JOptionPane.WARNING_MESSAGE
                );
                return;
            }

            double subtotal = price * quantity;

            DefaultTableModel model =
                    (DefaultTableModel) jTable1.getModel();

            model.addRow(new Object[]{
                medicineId,
                medicineName,
                price,
                quantity,
                subtotal
            });

            jTextField2.setText(String.format("%.2f", price));

            calculateTotal();

            jTextField1.setText("");

        }

    } catch (Exception e) {

        JOptionPane.showMessageDialog(
                this,
                "Database error:\n" + e.getMessage(),
                "Database Error",
                JOptionPane.ERROR_MESSAGE
        );

        e.printStackTrace();
    }

    }//GEN-LAST:event_jButton1ActionPerformed

