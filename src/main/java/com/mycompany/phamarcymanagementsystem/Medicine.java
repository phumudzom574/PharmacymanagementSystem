    private void loadMedicine(int medicineId) {

    String sql = "SELECT name, company, medicine_type, price, "
            + "quantity_in_stock, reorder_level, expiry_date, supplier_id "
            + "FROM medicines WHERE medicine_id = ?";

    try (
            Connection con = DBConnection.getConnection();
            PreparedStatement pst = con.prepareStatement(sql)
    ) {

        pst.setInt(1, medicineId);

        ResultSet rs = pst.executeQuery();

        if (rs.next()) {

            jTextField2.setText(rs.getString("name"));
            jTextField3.setText(rs.getString("company"));
            jTextField4.setText(rs.getString("medicine_type"));
            jTextField5.setText(String.valueOf(rs.getDouble("price")));
            jTextField6.setText(String.valueOf(rs.getInt("quantity_in_stock")));
            jTextField7.setText(String.valueOf(rs.getInt("reorder_level")));
            jTextField8.setText(rs.getDate("expiry_date").toString());
            jTextField9.setText(String.valueOf(rs.getInt("supplier_id")));
        }

    } catch (Exception e) {

        JOptionPane.showMessageDialog(
                this,
                "Database error:\n" + e.getMessage(),
                "Error",
                JOptionPane.ERROR_MESSAGE
        );

        e.printStackTrace();
    }
    }
