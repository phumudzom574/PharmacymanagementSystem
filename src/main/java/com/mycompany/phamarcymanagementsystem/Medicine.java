    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
    String name = jTextField2.getText().trim();
    String company = jTextField3.getText().trim();
    String medicineType = jTextField4.getText().trim();
    String price = jTextField5.getText().trim();
    String quantity = jTextField6.getText().trim();
    String reorderLevel = jTextField7.getText().trim();
    String expiryDate = jTextField8.getText().trim();
    String supplierId = jTextField9.getText().trim();

    if ( name.isEmpty() || company.isEmpty()
            || medicineType.isEmpty() || price.isEmpty()
            || quantity.isEmpty() || reorderLevel.isEmpty()
            || expiryDate.isEmpty() || supplierId.isEmpty()) {

        JOptionPane.showMessageDialog(
                this,
                "Please fill in all medicine details.",
                "Missing Information",
                JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    String sql = "INSERT INTO medicines "
            + "( name, company, medicine_type, price, "
            + "quantity_in_stock, reorder_level, expiry_date, supplier_id) "
            + "VALUES ( ?, ?, ?, ?, ?, ?, ?, ?)";

    try (
            Connection con = DBConnection.getConnection();
            PreparedStatement pst = con.prepareStatement(sql)
    ) {

        
       pst.setString(1, name);
pst.setString(2, company);
pst.setString(3, medicineType);
pst.setDouble(4, Double.parseDouble(price));
pst.setInt(5, Integer.parseInt(quantity));
pst.setInt(6, Integer.parseInt(reorderLevel));
pst.setDate(7, java.sql.Date.valueOf(expiryDate));
pst.setInt(8, Integer.parseInt(supplierId));

        pst.executeUpdate();

        JOptionPane.showMessageDialog(
                this,
                "Medicine added successfully!",
                "Success",
                JOptionPane.INFORMATION_MESSAGE
        );

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(
                this,
                "Medicine ID, Price, Quantity, Reorder Level and Supplier ID must contain valid numbers.",
                "Invalid Information",
                JOptionPane.WARNING_MESSAGE
        );

    } catch (IllegalArgumentException e) {

        JOptionPane.showMessageDialog(
                this,
                "Expiry Date must use this format: YYYY-MM-DD",
                "Invalid Date",
                JOptionPane.WARNING_MESSAGE
        );

    } catch (Exception e) {

        JOptionPane.showMessageDialog(
                this,
                "Database error:\n" + e.getMessage(),
                "Error",
                JOptionPane.ERROR_MESSAGE
        );

        e.printStackTrace();
    }

    }//GEN-LAST:event_jButton1ActionPerformed

