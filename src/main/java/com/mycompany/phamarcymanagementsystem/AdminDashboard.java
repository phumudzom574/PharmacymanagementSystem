    private void jButton11ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton11ActionPerformed
        // TODO add your handling code here:
      
    try {
        Connection con = ConnectionProvider.getcon();

        String sql = "SELECT name, quantity_in_stock, reorder_level "
                   + "FROM medicines "
                   + "WHERE quantity_in_stock <= reorder_level";

        PreparedStatement pst = con.prepareStatement(sql);
        ResultSet rs = pst.executeQuery();

        StringBuilder alert = new StringBuilder();

        while (rs.next()) {
            alert.append(rs.getString("name"))
                 .append(" - Stock: ")
                 .append(rs.getInt("quantity_in_stock"))
                 .append(" (Reorder Level: ")
                 .append(rs.getInt("reorder_level"))
                 .append(")\n");
        }

        if (alert.length() == 0) {
            JOptionPane.showMessageDialog(this,
                    "No medicines are low in stock.");
        } else {
            JOptionPane.showMessageDialog(this,
                    "LOW STOCK ALERT!\n\n" + alert.toString());
        }

        rs.close();
        pst.close();
        con.close();

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this,
                "Error: " + e.getMessage());
    }

    }//GEN-LAST:event_jButton11ActionPerformed

